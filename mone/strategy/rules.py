"""
mone.strategy.rules — Deterministic Quantitative Trading Strategy Engine.
Implements the core decision rules:
- Long YES if WeatherNext Model > 75% AND Entry Ask < 80c
- Long NO if WeatherNext Model < 25% AND Entry Ask < 80c
- NO TRADE if 25% <= Model <= 75% OR Ask >= 80c
"""

from typing import Literal, Optional
from pydantic import BaseModel, Field

from mone.config import MoneConfig
from mone.markets.base import MarketQuote
from mone.providers.base import WeatherForecast
from mone.strategy.edge import calculate_edge
from mone.strategy.sizing import calculate_position_size


class TradeSignal(BaseModel):
    """Normalized trading signal generated by deterministic strategy."""
    station_code: str
    city: str
    target_date: str
    market_id: str
    venue: str
    action: Literal["BUY_YES", "BUY_NO", "NO_TRADE"]
    side: Literal["YES", "NO", "NONE"]
    model_prob_pct: float
    market_ask: float
    market_implied_prob_pct: float
    edge_pct: float
    expected_roi_pct: float
    contracts_suggested: int
    capital_allocated: float
    reason: str
    is_actionable: bool


def evaluate_market_signal(
    forecast: WeatherForecast,
    quote: MarketQuote,
    config: Optional[MoneConfig] = None,
) -> TradeSignal:
    """
    Evaluates weather forecast against market quote using deterministic strategy rules.
    """
    if config is None:
        from mone.config import get_config
        config = get_config()

    code = forecast.station_code
    city = forecast.city
    target_date = forecast.target_date
    model_p = forecast.rain_probability_pct

    # Pre-condition: Forecast must be valid
    if not forecast.is_valid:
        return TradeSignal(
            station_code=code,
            city=city,
            target_date=target_date,
            market_id=quote.market_id,
            venue=quote.venue,
            action="NO_TRADE",
            side="NONE",
            model_prob_pct=model_p,
            market_ask=0.0,
            market_implied_prob_pct=0.0,
            edge_pct=0.0,
            expected_roi_pct=0.0,
            contracts_suggested=0,
            capital_allocated=0.0,
            reason=f"Forecast invalid: {forecast.error}",
            is_actionable=False,
        )

    # Condition 1: Long YES
    # Model > 75% and Yes Ask < 80c
    if model_p > config.long_yes_prob_threshold:
        yes_ask = quote.yes_ask
        if yes_ask <= 0:
            return TradeSignal(
                station_code=code,
                city=city,
                target_date=target_date,
                market_id=quote.market_id,
                venue=quote.venue,
                action="NO_TRADE",
                side="NONE",
                model_prob_pct=model_p,
                market_ask=0.0,
                market_implied_prob_pct=0.0,
                edge_pct=0.0,
                expected_roi_pct=0.0,
                contracts_suggested=0,
                capital_allocated=0.0,
                reason="No active YES ask price available on market order book",
                is_actionable=False,
            )

        if yes_ask >= config.max_entry_ask_price:
            return TradeSignal(
                station_code=code,
                city=city,
                target_date=target_date,
                market_id=quote.market_id,
                venue=quote.venue,
                action="NO_TRADE",
                side="NONE",
                model_prob_pct=model_p,
                market_ask=yes_ask,
                market_implied_prob_pct=round(yes_ask * 100.0, 1),
                edge_pct=round(model_p - (yes_ask * 100.0), 1),
                expected_roi_pct=0.0,
                contracts_suggested=0,
                capital_allocated=0.0,
                reason=f"YES ask ${yes_ask:.2f} >= safety ceiling ${config.max_entry_ask_price:.2f} (poor risk/reward)",
                is_actionable=False,
            )

        edge = (model_p / 100.0) - yes_ask
        if edge < config.min_edge_threshold:
            return TradeSignal(
                station_code=code,
                city=city,
                target_date=target_date,
                market_id=quote.market_id,
                venue=quote.venue,
                action="NO_TRADE",
                side="NONE",
                model_prob_pct=model_p,
                market_ask=yes_ask,
                market_implied_prob_pct=round(yes_ask * 100.0, 1),
                edge_pct=round(edge * 100.0, 1),
                expected_roi_pct=0.0,
                contracts_suggested=0,
                capital_allocated=0.0,
                reason=f"Statistical edge {edge*100.0:.1f}% below minimum threshold {config.min_edge_threshold*100.0:.1f}%",
                is_actionable=False,
            )

        contracts, invested = calculate_position_size(config.capital_per_trade, yes_ask)
        roi = round(((1.0 - yes_ask) / yes_ask) * 100.0, 1)

        return TradeSignal(
            station_code=code,
            city=city,
            target_date=target_date,
            market_id=quote.market_id,
            venue=quote.venue,
            action="BUY_YES",
            side="YES",
            model_prob_pct=model_p,
            market_ask=yes_ask,
            market_implied_prob_pct=round(yes_ask * 100.0, 1),
            edge_pct=round(edge * 100.0, 1),
            expected_roi_pct=roi,
            contracts_suggested=contracts,
            capital_allocated=invested,
            reason=f"Strong Rain Signal: Model {model_p:.1f}% > 75%, Ask ${yes_ask:.2f} < ${config.max_entry_ask_price:.2f}, Edge +{edge*100.0:.1f}%",
            is_actionable=True,
        )

    # Condition 2: Long NO
    # Model < 25% and No Ask < 80c
    elif model_p < config.long_no_prob_threshold:
        no_ask = quote.no_ask
        if no_ask <= 0:
            return TradeSignal(
                station_code=code,
                city=city,
                target_date=target_date,
                market_id=quote.market_id,
                venue=quote.venue,
                action="NO_TRADE",
                side="NONE",
                model_prob_pct=model_p,
                market_ask=0.0,
                market_implied_prob_pct=0.0,
                edge_pct=0.0,
                expected_roi_pct=0.0,
                contracts_suggested=0,
                capital_allocated=0.0,
                reason="No active NO ask price available on market order book",
                is_actionable=False,
            )

        if no_ask >= config.max_entry_ask_price:
            return TradeSignal(
                station_code=code,
                city=city,
                target_date=target_date,
                market_id=quote.market_id,
                venue=quote.venue,
                action="NO_TRADE",
                side="NONE",
                model_prob_pct=model_p,
                market_ask=no_ask,
                market_implied_prob_pct=round(no_ask * 100.0, 1),
                edge_pct=round((100.0 - model_p) - (no_ask * 100.0), 1),
                expected_roi_pct=0.0,
                contracts_suggested=0,
                capital_allocated=0.0,
                reason=f"NO ask ${no_ask:.2f} >= safety ceiling ${config.max_entry_ask_price:.2f} (poor risk/reward)",
                is_actionable=False,
            )

        no_model_p = (100.0 - model_p) / 100.0
        edge = no_model_p - no_ask
        if edge < config.min_edge_threshold:
            return TradeSignal(
                station_code=code,
                city=city,
                target_date=target_date,
                market_id=quote.market_id,
                venue=quote.venue,
                action="NO_TRADE",
                side="NONE",
                model_prob_pct=model_p,
                market_ask=no_ask,
                market_implied_prob_pct=round(no_ask * 100.0, 1),
                edge_pct=round(edge * 100.0, 1),
                expected_roi_pct=0.0,
                contracts_suggested=0,
                capital_allocated=0.0,
                reason=f"Statistical edge {edge*100.0:.1f}% below minimum threshold {config.min_edge_threshold*100.0:.1f}%",
                is_actionable=False,
            )

        contracts, invested = calculate_position_size(config.capital_per_trade, no_ask)
        roi = round(((1.0 - no_ask) / no_ask) * 100.0, 1)

        return TradeSignal(
            station_code=code,
            city=city,
            target_date=target_date,
            market_id=quote.market_id,
            venue=quote.venue,
            action="BUY_NO",
            side="NO",
            model_prob_pct=model_p,
            market_ask=no_ask,
            market_implied_prob_pct=round(no_ask * 100.0, 1),
            edge_pct=round(edge * 100.0, 1),
            expected_roi_pct=roi,
            contracts_suggested=contracts,
            capital_allocated=invested,
            reason=f"Strong Dry Signal: Model {model_p:.1f}% < 25% (Dry {100.0-model_p:.1f}%), Ask ${no_ask:.2f} < ${config.max_entry_ask_price:.2f}, Edge +{edge*100.0:.1f}%",
            is_actionable=True,
        )

    # Condition 3: Neutral Zone (25% to 75%)
    else:
        return TradeSignal(
            station_code=code,
            city=city,
            target_date=target_date,
            market_id=quote.market_id,
            venue=quote.venue,
            action="NO_TRADE",
            side="NONE",
            model_prob_pct=model_p,
            market_ask=quote.yes_ask,
            market_implied_prob_pct=quote.implied_yes_prob_pct,
            edge_pct=0.0,
            expected_roi_pct=0.0,
            contracts_suggested=0,
            capital_allocated=0.0,
            reason=f"Neutral forecast zone: Model probability {model_p:.1f}% sits between 25% and 75% (no mathematical edge)",
            is_actionable=False,
        )
